// The epilogue after the last night: who she was, what was ended. allDocs: every document of every
// night has been read at some point.
export function epilogue(allDocs) {
  const p = [
    'By noon the first lorries come up the valley road. The soldiers find the pump hall flooded, the yard gate open, and an old woman in a nurse\'s uniform lying in the mud with a broken lantern beside her.',
    'Nobody in Wolf Hollow sleeps that night. Then, one by one, they do.'
  ];
  if (allDocs) p.push('You give them everything: the admissions ledger, the doctor\'s journal, the deed, the wages for men who did not need lamps, the letters nobody sent. Batch 115/11 is never found. But this time, someone is listening.');
  else p.push('Of the doctor and his last batch there is no sign. Somewhere, a box marked 115/11 is still waiting.');
  return p;
}
