// Pick the ending text from how the night went.
export function ending(mapId, W, players, meId, prefix) {
  const me = players.find(p => p.id === meId);
  const escaped = players.filter(p => p.st === 'e');
  const T = TEXT[mapId] || TEXT.sanatorium;
  const total = Object.keys(NOTES).filter(k => k[0] === prefix).length;
  const allNotes = W.notes.filter(n => n[0] === prefix).length >= total;
  if (W.result !== 'escaped') return { title: players.length > 1 ? 'Nobody made it out' : 'You died', text: T.dead };
  const mine = me && me.st === 'e';
  const lost = players.length - escaped.length;
  let title = mine ? 'You escaped' : 'Some of you escaped';
  let text = lost ? T.lost : T.all;
  if (allNotes) { if (mine) title = 'You escaped with the truth'; text += T.truth; }
  return { title, text, allNotes };
}
